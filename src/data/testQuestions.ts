export function calculateTestResult(answers: number[]): {
  score: number;
  percentage: number;
  level: string;
  description: string;
} {
  const score = answers.reduce((sum, val) => sum + val, 0);
  const maxScore = (testQuestions.length - 1) * 4;
  const percentage = Math.round((score / maxScore) * 100);

  let level = '';
  let description = '';

  if (percentage >= 70) {
    level = 'Высокий уровень выгорания';
    description = 'Рекомендуется срочно принять меры. Обратитесь к специалисту и начните работу над восстановлением.';
  } else if (percentage >= 40) {
    level = 'Средний уровень выгорания';
    description = 'Важно начать работать над восстановлением. Пройдите курс и внедрите техники профилактики.';
  } else {
    level = 'Низкий уровень выгорания';
    description = 'Продолжайте поддерживать баланс. Используйте профилактические техники для сохранения здоровья.';
  }

  return { score, percentage, level, description };
}
